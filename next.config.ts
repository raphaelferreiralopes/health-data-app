import type { NextConfig } from "next";

// Wildcarded rather than the specific project ref so this doesn't need
// updating per Supabase project/environment.
const SUPABASE_CONNECT_SRC = 'https://*.supabase.co wss://*.supabase.co';

const contentSecurityPolicy = [
  "default-src 'self'",
  // Next.js ships some inline bootstrap/hydration scripts, so a strict
  // nonce-based policy isn't practical here without deeper CSP plumbing.
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self' data:",
  `connect-src 'self' ${SUPABASE_CONNECT_SRC}`,
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join('; ');

const securityHeaders = [
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },
  { key: 'Content-Security-Policy', value: contentSecurityPolicy },
];

const nextConfig: NextConfig = {
  async headers() {
    return [
      {
        source: '/(.*)',
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
